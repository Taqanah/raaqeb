/** A URL's host, or nothing readable when it does not parse. */
function hostOf(url: string | undefined): string {
  return url !== undefined && URL.canParse(url) ? new URL(url).host : "";
}

/** A channel's stored fields: everything but its secrets. */
export interface ChannelFields {
  readonly appliesToNew: boolean;
  /** The values of the fields that are not secret, by name. */
  readonly config: Readonly<Record<string, string>>;
  /** Absent follows the install language (CONTEXT.md "Channel language"). */
  readonly locale: Locale | undefined;
  readonly name: string;
  readonly type: ChannelType;
}

/** A channel as the repository answers it: never a secret. */
export interface Channel extends ChannelFields {
  readonly createdAt: number;
  readonly id: string;
  readonly updatedAt: number;
}

/** What create and edit post: a typed value for each declared field that is not generated; a secret left out keeps the stored one. */
export const channelInputSchema = z.object({
  appliesToNew: z.boolean(),
  locale: localeSchema.optional(),
  name: z.string().trim().min(1).max(channelNameMaxLength),
  type: channelTypeSchema,
  values: z.record(z.string(), z.string()),
});
export type ChannelInput = z.infer<typeof channelInputSchema>;

export const channelEditSchema = z.object({
  id: z.string().min(1),
  input: channelInputSchema,
  /** Every generated field gets a new value on this save; a receiver holding the old one stops verifying. */
  renewGenerated: z.boolean().optional(),
});
export type ChannelEditInput = z.infer<typeof channelEditSchema>;

export const channelIdSchema = z.object({ id: z.string().min(1) });

/** Why a channel write or a send test did not happen. */
export type ChannelRefusal = "invalid" | "not_found" | "unavailable";

/** One channel on the list: what it is, what it reaches and how its newest notification went. */
export interface ChannelListItem {
  readonly channel: Channel;
  readonly last: Notification | undefined;
  /** The declaration's summary of its values; empty when the install key cannot open them. */
  readonly summary: string;
}

export type ChannelListResult =
  | { readonly ok: true; readonly channels: readonly ChannelListItem[] }
  | { readonly ok: false; readonly reason: "unavailable" }
  /** A stored channel this version cannot read; `id` names it. */
  | { readonly ok: false; readonly reason: "corrupt"; readonly id: string };

/** The channel page's read: the channel, what its form may show of the secrets, its notification preview and its recent sends. */
export interface ChannelForm {
  readonly channel: Channel;
  /** The generated values, shown so the receiver can be given them. */
  readonly generated: Readonly<Record<string, string>>;
  /** The typed secret fields that have a stored value, which an empty field keeps. */
  readonly kept: readonly string[];
  /** The notification preview: one sample of each operator notification the channel can receive. */
  readonly preview: readonly NotificationPreview[];
  /** Newest first. */
  readonly recent: readonly Notification[];
  readonly summary: string;
}

/** A URL in a notification, with the words that open it where the channel can link. */
export interface NotificationLink {
  readonly url: string;
  readonly words: string;
}

/** The media query an email's HTML part draws its dark colours under; the preview swaps it for the admin's theme. */
export const emailDarkQuery = "@media (prefers-color-scheme: dark)";

/** One operator notification as the channel's type carries it, with sample values (CONTEXT.md "Notification preview"). */
export interface NotificationPreview {
  /** The chat message as the app shows it, its links apart, the email's or ntfy's text, or the webhook's JSON body. */
  readonly body: string;
  /** The buttons under the message, as ntfy shows its view actions. */
  readonly buttons: readonly NotificationLink[];
  /** The email's HTML part, which the preview shows in a sandboxed frame; no other type has one. */
  readonly html: string | undefined;
  /** The words that open a URL on lines of their own after the body, as a chat message shows them. */
  readonly links: readonly NotificationLink[];
  /** The email's subject or ntfy's title; a chat message carries it as its first line and the webhook has none. */
  readonly subject: string | undefined;
  readonly type: Exclude<NotificationType, "channel.test">;
}

export type ChannelFormResult =
  | { readonly ok: true; readonly form: ChannelForm }
  | { readonly ok: false; readonly reason: "not_found" | "unavailable" }
  | { readonly ok: false; readonly reason: "corrupt"; readonly id: string };

export type ChannelSaveResult =
  | { readonly ok: true; readonly channel: Channel }
  | { readonly ok: false; readonly reason: ChannelRefusal };

export type ChannelDeleteResult =
  | { readonly ok: true }
  | { readonly ok: false; readonly reason: ChannelRefusal };

/** "Send test": the one attempt's outcome as its recent sends row records it. */
