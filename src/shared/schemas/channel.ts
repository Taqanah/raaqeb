/** The ntfy server a new channel starts at. */
export const ntfyPublicServer = "https://ntfy.sh";

/** An ntfy server's address: an origin with no path, since ntfy takes a JSON publish only at its root and a path would publish to a topic of that name. */
const ntfyServer = webhookUrl.refine(
  (url) => !URL.canParse(url) || `${new URL(url).origin}/` === new URL(url).href
);

