/**
 * A notification channel (CONTEXT.md "Notification channel"): a
 * destination the install owns, with a name, a type, its declared config
 * fields, a channel language and the "apply to new monitors by default"
 * flag. Each type declares its fields here, so the admin form renders
 * itself; the server side of a type, its `send`, lives in server/notify.
 * Secret fields are sealed with the install key; a typed one is write-only
 * in the form and a generated one is shown.
 */
import { z } from "zod";
import { type Locale, localeSchema } from "@/shared/i18n/locale.ts";
import type { MessageId } from "@/shared/i18n/messages.ts";
import type { Notification, NotificationType } from "./notification.ts";

export const channelTypes = [
  "webhook",
  "email",
  "slack",
  "discord",
  "telegram",
  "ntfy",
] as const;
export const channelTypeSchema = z.enum(channelTypes);
export type ChannelType = z.infer<typeof channelTypeSchema>;

export const channelNameMaxLength = 80;
/** The longest URL a channel stores; webhook URLs with a token in the path stay well under it. */
export const channelUrlMaxLength = 2048;

/** How the form draws a field: typed as a URL or as text, chosen from a list, or generated by Raaqeb and shown with a switch that renews it. */
export type ChannelFieldKind = "url" | "text" | "select" | "generated";

/** One choice of a select field. */
export interface ChannelFieldOption {
  /** What the form says under the field while this choice is selected, in place of the field's own hint. */
  readonly hint?: MessageId;
  readonly label: MessageId;
  readonly value: string;
}

/** The values a channel's fields hold, by field name; a field may have none. */
export type ChannelValues = Readonly<Partial<Record<string, string>>>;

/** One config field a channel type declares. */
export interface ChannelField {
  readonly hint?: MessageId;
  /** A new channel's value; a select starts at it. */
  readonly initial?: string;
  readonly kind: ChannelFieldKind;
  readonly label: MessageId;
  readonly name: string;
  /** May be left empty; every other field that applies is required. */
  readonly optional?: boolean;
  /** A select's choices. */
  readonly options?: readonly ChannelFieldOption[];
  /** What the form says of a value that does not fit; the kind's own refusal otherwise. */
  readonly refusal?: MessageId;
  /** Sealed with the install key; a typed secret the form leaves empty keeps the stored value. */
  readonly secret: boolean;
  /** A typed secret the operator reads to type elsewhere, such as an ntfy topic: shown while typed, sealed at rest all the same. */
  readonly shown?: boolean;
  /** What a value must be. */
  readonly value: z.ZodType<string>;
  /** Whether the field applies, given the values typed in clear; absent applies always. A field that does not apply is neither shown nor stored. */
  readonly when?: (values: ChannelValues) => boolean;
}

/** What a channel type declares for the admin area. */
export interface ChannelDeclaration {
  readonly fields: readonly ChannelField[];
  /** The type's chip, like HTTP or TCP for a check type. */
  readonly label: MessageId;
  /** Whether its messages are text in the channel language; the webhook's payload is machine values and never localized. */
  readonly localized: boolean;
  /** What the list shows of a channel from its values, secrets included, never a secret itself: the webhook's host, the email's recipients. */
  readonly summary: (values: ChannelValues) => string;
  readonly type: ChannelType;
}

/** A Standard Webhooks signing secret: `whsec_` and the base64 of 32 random bytes. */
export const signingSecretShape = /^whsec_[A-Za-z0-9+/]{43}=$/;

const webhookUrl = z
  .url({ protocol: /^https?$/ })
  .max(channelUrlMaxLength)
  // Port 0 reaches nothing.
  .refine((url) => !URL.canParse(url) || new URL(url).port !== "0");

/** The generic webhook: a signed JSON POST to one URL, which counts as a secret since it often carries a token. */
export const webhookDeclaration: ChannelDeclaration = {
  fields: [
    {
      hint: "channel_field_url_hint",
      kind: "url",
      label: "channel_field_url",
      name: "url",
      secret: true,
      value: webhookUrl,
    },
    {
      hint: "channel_field_signing_secret_hint",
      kind: "generated",
      label: "channel_field_signing_secret",
      name: "secret",
      secret: true,
      value: z.string().regex(signingSecretShape),
    },
  ],
  label: "channel_type_webhook",
  localized: false,
  summary: (values) => hostOf(values.url),
  type: "webhook",
};

/** The fields of a declaration that apply to these values, in declared order. */
export function fieldsFor(
  declaration: ChannelDeclaration,
  values: ChannelValues
): readonly ChannelField[] {
  return declaration.fields.filter((field) => field.when?.(values) ?? true);
}

/** What the form says under a field holding this value: the selected choice's own hint, else the field's, so the line stays true as the choice changes. */
export function hintFor(
  field: ChannelField,
  value: string | undefined
): MessageId | undefined {
  return (
    field.options?.find((option) => option.value === value)?.hint ?? field.hint
  );
}

/** How an SMTP connection is protected: STARTTLS on a plain connection, TLS from the first byte, or nothing, for a relay on the same host or network. */
export const smtpSecurities = ["starttls", "tls", "none"] as const;
export type SmtpSecurity = (typeof smtpSecurities)[number];

/** The most addresses one email channel sends to. */
export const recipientsMax = 10;

/** A display name with no quote, comma, angle bracket or control character, then the address in angle brackets; or the address alone. A line break would reach a provider's header. */
const senderShape = /^(?:([^"<>,\p{Cc}]+)<([^<>\s]+)>|([^<>\s]+))$/u;
const recipientSeparator = /[,،]/;

/** An email sender: its address, and the display name before it when one was typed. */
export interface Sender {
  readonly address: string;
  readonly name: string | undefined;
}

/** A sender as typed, `alerts@raaqeb.dev` or `Raaqeb <alerts@raaqeb.dev>`; nothing when it is neither. */
export function senderOf(text: string): Sender | undefined {
  const [, name, bracketed, bare] = senderShape.exec(text.trim()) ?? [];
  const address = bracketed ?? bare;
  if (address === undefined || !z.email().safeParse(address).success) {
    return;
  }
  return { address, name: name?.trim() };
}

/** The recipients typed in one field, split on the Latin or the Arabic comma, blanks dropped. */
export function recipientsOf(text: string): string[] {
  return text
    .split(recipientSeparator)
    .map((each) => each.trim())
    .filter((each) => each !== "");
}

/** Whether an SMTP connection is protected, so a user name may be sent; AUTH never crosses a plain connection. */
function overProtectedSmtp(values: ChannelValues): boolean {
  return values.security !== "none";
}

/** Whether a user name was typed for a protected SMTP connection, which then needs its password. */
function withSmtpUser(values: ChannelValues): boolean {
  return overProtectedSmtp(values) && (values.username ?? "").trim() !== "";
}

const secretMaxLength = 1024;

const sender = z
  .string()
  .max(320)
  .refine((text) => senderOf(text) !== undefined);

const recipients = z
  .string()
  .max(recipientsMax * 320)
  .refine((text) => {
    const each = recipientsOf(text);
    return (
      each.length > 0 &&
      each.length <= recipientsMax &&
      each.every((address) => z.email().safeParse(address).success)
    );
  });

const port = z
  .string()
  .regex(/^\d{1,5}$/)
  .refine((text) => Number(text) >= 1 && Number(text) <= 65_535);

