/**
 * Writes `src/admin/settings/zone-cities.ts`: the city each time zone is
 * named for, in Arabic and in English, from Unicode CLDR. The browser names a
 * zone's region (`التوقيت العربي الرسمي`) but no browser exposes the city,
 * which tells apart the zones sharing a region. CLDR keys a few zones by
 * older names (Asia/Calcutta for Asia/Kolkata); its alias table maps them.
 * Run `bun run zones` after a CLDR release; the version is pinned here so the
 * file only changes when this line does.
 */
import { $ } from "bun";

const cldrVersion = "48.2.3";
const base = `https://raw.githubusercontent.com/unicode-org/cldr-json/${cldrVersion}/cldr-json`;
const output = "src/admin/settings/zone-cities.ts";

interface ZoneNode {
  readonly [key: string]: ZoneNode | string;
}

async function json(path: string): Promise<unknown> {
  const response = await fetch(`${base}/${path}`);
  if (!response.ok) {
    throw new Error(`${path}: ${response.status}`);
  }
  return response.json();
}

/** Every zone id under the tree with its exemplar city. */
function cities(tree: ZoneNode, path: string[] = []): Map<string, string> {
  const found = new Map<string, string>();
  for (const [key, value] of Object.entries(tree)) {
    if (typeof value === "string") {
      continue;
    }
    const city = value.exemplarCity;
    if (typeof city === "string") {
      found.set([...path, key].join("/"), city);
    } else {
      for (const [id, name] of cities(value, [...path, key])) {
        found.set(id, name);
      }
    }
  }
  return found;
}

function zoneTree(data: unknown, locale: string): ZoneNode {
  const names = (
    data as {
      main: Record<string, { dates: { timeZoneNames: { zone: ZoneNode } } }>;
    }
  ).main[locale];
  if (!names) {
    throw new Error(`no ${locale} time zone names`);
  }
  return names.dates.timeZoneNames.zone;
}

const [ar, en, bcp47] = await Promise.all([
  json("cldr-dates-full/main/ar/timeZoneNames.json"),
  json("cldr-dates-full/main/en/timeZoneNames.json"),
  json("cldr-bcp47/bcp47/timezone.json"),
]);
const arabic = cities(zoneTree(ar, "ar"));
const english = cities(zoneTree(en, "en"));

// Each alias line names one zone: CLDR's own id first, then the other names it goes by.
const aliases = new Map<string, readonly string[]>();
const entries = (bcp47 as { keyword: { u: { tz: Record<string, unknown> } } })
  .keyword.u.tz;
for (const entry of Object.values(entries)) {
  const alias =
    typeof entry === "object" && entry !== null && "_alias" in entry
      ? String(entry._alias)
      : "";
  const ids = alias.split(" ").filter((id) => id.includes("/"));
  for (const id of ids) {
    aliases.set(id, ids);
  }
}

const nameOf = (names: Map<string, string>, zone: string) =>
  [zone, ...(aliases.get(zone) ?? [])]
    .map((id) => names.get(id))
    .find((name) => name !== undefined);

const rows: string[] = [];
const missing: string[] = [];
for (const zone of Intl.supportedValuesOf("timeZone")) {
  const city = nameOf(arabic, zone);
  // CLDR's English leaves out a city that is its id's last part with spaces (Asia/Riyadh is Riyadh).
  const latin =
    nameOf(english, zone) ?? zone.split("/").at(-1)?.replaceAll("_", " ");
  if (city && latin) {
    rows.push(
      `  ${JSON.stringify(zone)}: [${JSON.stringify(city)}, ${JSON.stringify(latin)}],`
    );
  } else {
    missing.push(zone);
  }
}

await Bun.write(
  output,
  `// Generated by scripts/zone-cities.ts from Unicode CLDR ${cldrVersion}; do not edit.
// Copyright © 1991-2025 Unicode, Inc. Unicode License v3: https://www.unicode.org/license.txt
// Each zone's city, [Arabic, English]; a zone with no city (UTC, Etc/GMT+3) is not here.

export const zoneCities: Readonly<
  Record<string, readonly [ar: string, en: string]>
> = {
${rows.join("\n")}
};
`
);
await $`bunx biome format --write ${output}`.quiet();
console.log(
  `${rows.length} zones written; without a city: ${missing.join(" ")}`
);
